-- =============================================================================
-- โครงสร้างฐานข้อมูล — ระบบจัดการข้อมูลหลักสูตรปริญญาตรี
-- =============================================================================
-- ตรวจเทียบกับ models.py ทีละบรรทัดแล้ว (v2)
--   9 ตาราง, ชื่อตารางเป็นพหูพจน์, FK หมวดแม่ = parent_group_id
--   enum: grouptype (5 ค่า), equivalencetype (2 ค่า)
--
-- ⚠️ คำเตือน: ถ้าแอปใช้ Base.metadata.create_all() อยู่แล้ว "ไม่ต้องรันไฟล์นี้"
--    ไฟล์นี้มีไว้เพื่อ (ก) อ่านทำความเข้าใจสคีมา (ข) ตั้ง DB เองโดยไม่ผ่าน ORM
--    (ค) ใช้เป็นฐานในการย้ายไป DB อื่น
--
-- เป้าหมาย: PostgreSQL 12+ (ดูภาคผนวก SQLite ท้ายไฟล์)
-- NOTE: SQLAlchemy ตั้งชื่อ native enum type จากชื่อ class ของ enum → grouptype,
--       equivalencetype (ในไฟล์นี้ตั้งชื่อให้ตรงตามนั้นเพื่อความสอดคล้อง)
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- ENUM TYPES
-- -----------------------------------------------------------------------------
CREATE TYPE grouptype AS ENUM (
    'GENED',                -- ศึกษาทั่วไป (หมวดกลางของสถาบัน)
    'MAJOR_REQUIRED',       -- วิชาเฉพาะ - บังคับ
    'MAJOR_ELECTIVE',       -- วิชาเฉพาะ - เลือกสาขา
    'RESTRICTED_ELECTIVE',  -- วิชาเฉพาะ - บังคับเลือก
    'FREE_ELECTIVE'         -- เลือกเสรี
);

CREATE TYPE equivalencetype AS ENUM (
    'FULL',     -- เทียบเท่าเต็มหน่วยกิต
    'PARTIAL'   -- เทียบได้บางส่วน (ดู credit_equivalent)
);

-- -----------------------------------------------------------------------------
-- 1) curricula
-- -----------------------------------------------------------------------------
CREATE TABLE curricula (
    id             integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(255) NOT NULL,
    faculty        varchar(255),                  -- nullable ตาม models.py
    year           integer      NOT NULL,         -- ปีหลักสูตร (พ.ศ.)
    total_credits  integer      NOT NULL,
    display_order  integer      NOT NULL DEFAULT 0
);
COMMENT ON TABLE  curricula IS 'หลักสูตร; seed มี 3 แถว (122 / 138 / 118)';
COMMENT ON COLUMN curricula.total_credits IS 'Integer ตาม models.py (ไม่รองรับหน่วยกิตมีทศนิยม)';
COMMENT ON COLUMN curricula.display_order IS 'น้อย = แสดงก่อน: IoT=1, ComIoT=2, Physics=3';

-- -----------------------------------------------------------------------------
-- 2) courses  (คลังรายวิชากลาง; PK = รหัสวิชา)
-- -----------------------------------------------------------------------------
CREATE TABLE courses (
    code         varchar(20)  PRIMARY KEY,
    name_th      varchar(255) NOT NULL,
    name_en      varchar(255),
    credits      integer      NOT NULL,   -- 0 ได้ (ฝึกงาน/สัมมนา) — models.py ไม่มี CHECK
    description  text
);
COMMENT ON TABLE courses IS 'ไม่มี constraint ใด ๆ ใน models.py (ไม่มี table_args)';

-- -----------------------------------------------------------------------------
-- 3) course_groups  (tree: หมวดใหญ่ -> หมวดย่อย)
--    curriculum_id NULL = หมวดกลางของสถาบัน (GenEd) ใช้ร่วมทุกหลักสูตร
-- -----------------------------------------------------------------------------
CREATE TABLE course_groups (
    id               integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             varchar(255) NOT NULL,
    group_type       grouptype    NOT NULL,
    parent_group_id  integer      REFERENCES course_groups (id) ON DELETE CASCADE,
    curriculum_id    integer      REFERENCES curricula (id)     ON DELETE CASCADE
);
COMMENT ON COLUMN course_groups.parent_group_id IS 'NULL = หมวดใหญ่ระดับบนสุด';
COMMENT ON COLUMN course_groups.curriculum_id   IS 'NULL = หมวดกลางของสถาบัน (GenEd) แชร์ทุกหลักสูตร';

-- -----------------------------------------------------------------------------
-- 4) study_plans
-- -----------------------------------------------------------------------------
CREATE TABLE study_plans (
    id             integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id  integer      NOT NULL REFERENCES curricula (id) ON DELETE CASCADE,
    code           varchar(50)  NOT NULL,   -- PROJECT | COOP | OVERSEA_TRAINING
    name           varchar(255) NOT NULL,
    CONSTRAINT uq_study_plan_code UNIQUE (curriculum_id, code)
);

-- -----------------------------------------------------------------------------
-- 5) curriculum_courses  (วิชา <-> หมวด <-> หลักสูตร <-> แผน + ปี/เทอมที่แนะนำ)
-- -----------------------------------------------------------------------------
CREATE TABLE curriculum_courses (
    id                    integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id         integer     NOT NULL REFERENCES curricula (id)      ON DELETE CASCADE,
    course_code           varchar(20) NOT NULL REFERENCES courses (code)      ON DELETE CASCADE,
    group_id              integer     NOT NULL REFERENCES course_groups (id)  ON DELETE CASCADE,
    study_plan_id         integer              REFERENCES study_plans (id)    ON DELETE CASCADE,
    is_required           boolean     NOT NULL,
    recommended_year      integer,
    recommended_semester  integer,
    CONSTRAINT uq_curriculum_course_group_plan
        UNIQUE (curriculum_id, course_code, group_id, study_plan_id),
    CONSTRAINT ck_recommended_semester_valid
        CHECK (recommended_semester IN (1, 2, 3))
);
COMMENT ON COLUMN curriculum_courses.study_plan_id IS 'NULL = วิชานี้ใช้เหมือนกันทุกแผน; มีค่า = เฉพาะแผนนั้น';
COMMENT ON COLUMN curriculum_courses.is_required    IS 'True = บังคับ / False = เลือก (default เป็น Python-side)';
COMMENT ON CONSTRAINT ck_recommended_semester_valid ON curriculum_courses
    IS 'ระวัง: ค่า NULL จะผ่าน CHECK นี้ได้ (SQL ถือ unknown ไม่ใช่ false)';

-- -----------------------------------------------------------------------------
-- 6) curriculum_group_requirements  (หน่วยกิตขั้นต่ำ/สูงสุด ต่อหมวด)
-- -----------------------------------------------------------------------------
CREATE TABLE curriculum_group_requirements (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id  integer NOT NULL REFERENCES curricula (id)     ON DELETE CASCADE,
    group_id       integer NOT NULL REFERENCES course_groups (id) ON DELETE CASCADE,
    min_credits    integer NOT NULL,
    max_credits    integer,   -- nullable; seed ไม่เคยใช้
    CONSTRAINT uq_curriculum_group_requirement UNIQUE (curriculum_id, group_id)
);
COMMENT ON TABLE curriculum_group_requirements IS
    'seed 25 แถว; ผลบวกต่อหลักสูตร = 122 / 138 / 118 พอดี';

-- -----------------------------------------------------------------------------
-- 7) elective_term_slots  (จำนวน "ช่อง" วิชาเลือกต่อหมวด/เทอม/แผน)
-- -----------------------------------------------------------------------------
CREATE TABLE elective_term_slots (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id  integer NOT NULL REFERENCES curricula (id)     ON DELETE CASCADE,
    group_id       integer NOT NULL REFERENCES course_groups (id) ON DELETE CASCADE,
    study_plan_id  integer          REFERENCES study_plans (id)   ON DELETE CASCADE,
    year           integer NOT NULL,
    semester       integer NOT NULL,
    slot_count     integer NOT NULL,
    CONSTRAINT uq_elective_term_slot
        UNIQUE (curriculum_id, group_id, study_plan_id, year, semester),
    CONSTRAINT ck_elective_slot_semester_valid CHECK (semester IN (1, 2, 3)),
    CONSTRAINT ck_elective_slot_count_positive CHECK (slot_count > 0)
);
COMMENT ON TABLE elective_term_slots IS 'seed 26 แถว: IoT 11 (มี plan 6) + Physics 8 + ComIoT 7';

-- -----------------------------------------------------------------------------
-- 8) course_grades  (ผลการเรียนจริง — ขอบเขตผู้ใช้คนเดียว ไม่มี Student entity)
-- -----------------------------------------------------------------------------
CREATE TABLE course_grades (
    id               integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id    integer     NOT NULL REFERENCES curricula (id) ON DELETE CASCADE,
    course_code      varchar(20) NOT NULL REFERENCES courses (code) ON DELETE CASCADE,
    grade            varchar(2)  NOT NULL,   -- A, B+, B, C+, C, D+, D, F, S, U
    actual_year      integer,
    actual_semester  integer,
    CONSTRAINT uq_course_grade_curriculum_course UNIQUE (curriculum_id, course_code)
    -- NOTE: ไม่มี CHECK ตรวจค่าเกรดที่ถูกต้องใน models.py; ไม่รองรับการเรียนซ้ำ
);
COMMENT ON TABLE course_grades IS 'seed ไม่แตะตารางนี้ (0 แถว)';

-- -----------------------------------------------------------------------------
-- 9) course_equivalencies  (คู่วิชาเทียบเคียง — สมมาตร ไม่มีทิศทาง)
-- -----------------------------------------------------------------------------
CREATE TABLE course_equivalencies (
    id                 integer          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code_a      varchar(20)      NOT NULL REFERENCES courses (code) ON DELETE CASCADE,
    course_code_b      varchar(20)      NOT NULL REFERENCES courses (code) ON DELETE CASCADE,
    equivalence_type   equivalencetype  NOT NULL,
    credit_equivalent  integer,   -- ใช้เมื่อ PARTIAL; seed ไม่เคยใช้
    note               text,
    CONSTRAINT ck_equivalency_not_self CHECK (course_code_a <> course_code_b)
    -- NOTE: models.py ไม่มี UNIQUE → (a,b) และ (b,a) เก็บซ้ำได้ ต้องกันที่ระดับแอป
);
COMMENT ON TABLE course_equivalencies IS 'seed 110 แถว (34 + 76) เป็น FULL ทั้งหมด';

-- =============================================================================
-- INDEX ที่แนะนำเพิ่ม (models.py ไม่มีเลย — FK ไม่ได้ถูก index อัตโนมัติ)
-- =============================================================================
CREATE INDEX ix_course_groups_parent      ON course_groups (parent_group_id);
CREATE INDEX ix_course_groups_curriculum  ON course_groups (curriculum_id);

CREATE INDEX ix_study_plans_curriculum    ON study_plans (curriculum_id);

CREATE INDEX ix_cc_curriculum             ON curriculum_courses (curriculum_id);
CREATE INDEX ix_cc_course                 ON curriculum_courses (course_code);
CREATE INDEX ix_cc_group                  ON curriculum_courses (group_id);
CREATE INDEX ix_cc_study_plan             ON curriculum_courses (study_plan_id);

CREATE INDEX ix_cgr_curriculum            ON curriculum_group_requirements (curriculum_id);
CREATE INDEX ix_cgr_group                 ON curriculum_group_requirements (group_id);

CREATE INDEX ix_ets_curriculum_term       ON elective_term_slots (curriculum_id, year, semester);
CREATE INDEX ix_ets_group                 ON elective_term_slots (group_id);

CREATE INDEX ix_course_grades_curriculum  ON course_grades (curriculum_id);
CREATE INDEX ix_course_grades_course      ON course_grades (course_code);

CREATE INDEX ix_equiv_a                   ON course_equivalencies (course_code_a);
CREATE INDEX ix_equiv_b                   ON course_equivalencies (course_code_b);

-- -----------------------------------------------------------------------------
-- Partial unique index: ปิดช่องโหว่ NULL ของ UNIQUE ที่มี study_plan_id
--   (ใน SQL ค่า NULL ไม่ถือว่าซ้ำกัน → แถวที่ study_plan_id IS NULL ซึ่งเป็นกลุ่ม
--    "ใช้ร่วมทุกแผน" จึงใส่ซ้ำได้ไม่จำกัด)
-- -----------------------------------------------------------------------------
CREATE UNIQUE INDEX uq_cc_shared
    ON curriculum_courses (curriculum_id, course_code, group_id)
    WHERE study_plan_id IS NULL;

CREATE UNIQUE INDEX uq_ets_shared
    ON elective_term_slots (curriculum_id, group_id, year, semester)
    WHERE study_plan_id IS NULL;

-- -----------------------------------------------------------------------------
-- ทางเลือก: กันคู่เทียบเคียงซ้ำแบบไม่สนทิศทาง
-- -----------------------------------------------------------------------------
CREATE UNIQUE INDEX uq_equiv_pair
    ON course_equivalencies (LEAST(course_code_a, course_code_b), GREATEST(course_code_a, course_code_b));

COMMIT;

-- =============================================================================
-- ภาคผนวก: SQLite (ถ้า init_db() ต่อ SQLite เป็นหลัก)
-- =============================================================================
-- SQLAlchemy บน SQLite จะไม่ใช้ native ENUM แต่สร้างเป็น VARCHAR + CHECK
-- ตัวอย่างการแปลง:
--
--   group_type varchar(20) NOT NULL
--       CHECK (group_type IN ('GENED','MAJOR_REQUIRED','MAJOR_ELECTIVE',
--                             'RESTRICTED_ELECTIVE','FREE_ELECTIVE'))
--
--   equivalence_type varchar(10) NOT NULL
--       CHECK (equivalence_type IN ('FULL','PARTIAL'))
--
--   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY  ->  integer PRIMARY KEY AUTOINCREMENT
--   ไม่มี COMMENT ON ...                                  ->  ย้ายไปเป็นคอมเมนต์ --
--   ไม่มี partial unique index                            -> ใช้ partial index ของ SQLite ได้
--       CREATE UNIQUE INDEX uq_cc_shared ON curriculum_courses
--           (curriculum_id, course_code, group_id) WHERE study_plan_id IS NULL;
--   ต้องเปิด  PRAGMA foreign_keys = ON;  ทุก connection ไม่งั้น ON DELETE CASCADE ไม่ทำงาน
-- =============================================================================
